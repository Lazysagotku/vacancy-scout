def _themes_for(matched: list[tuple[str, str]], text: str, themes=None) -> list[str]:
    """Выбирает тематические блоки под совпавшие навыки и текст вакансии.

    Порядок тем сохраняется: сначала то, что чаще всего оказывается главным
    требованием, потом остальное. Больше четырёх блоков не берём - длинное
    письмо дочитывают хуже короткого.
    """
    names = " ".join(name.lower() for name, _ in matched)
    low = text.lower()

    # Тему берём, если она есть в совпадениях ИЛИ если вакансия сама про неё
    # говорит. Порог по тексту снижен до одного упоминания: раньше стояло три,
    # и письмо на вакансию про Linux с Grafana выходило без абзаца про
    # инфраструктуру, потому что каждое слово встречалось по разу.
    scored = []
    for i, (title, keys, block) in enumerate(themes or THEMES):
        weight = sum(3 for k in keys if k in names) + sum(low.count(k) for k in keys)
        # Первая тема набора - главная для этого типа письма: у разработчика
        # это сам стек. Без бонуса её обгоняли «Инструменты» - git и docker
        # упоминаются в любой вакансии по десять раз.
        if weight and themes and i == 0:
            weight += 20
        if weight:
            scored.append((weight, block))

    scored.sort(key=lambda pair: -pair[0])
    return [block for _, block in scored[:4]]


def draft(vacancy: Vacancy, verdict: Verdict, form: dict | None = None) -> str:
    """Собирает черновик. Для отсеянных вакансий письма нет - незачем.

    Если форма отклика уже разведана и в ней есть вопросы работодателя,
    темы, о которых спросят отдельным полем, из письма убираются: работодатель
    иначе прочитает один ответ дважды.
    """
    if verdict.blockers:
        return ""

    track = verdict.track or "support"
    themes = None
    if track == "dev":
        # Разработчику - под его язык. Без языка в заголовке и описании
        # берём C#: он основной на последнем месте.
        lang = profile.dev_lang(vacancy.name, vacancy.haystack) or "csharp"
        track = lang
        themes = DEV_THEMES[lang]
    # Название берём как есть: lower() портил аббревиатуры и превращал
    # «L2 (Middle/Linux)» в «l2 (middle/linux)» - в письме это выглядит
    # неряшливо, будто текст собран машиной.
    parts = [OPENING.get(track, OPENING["support"]).format(name=vacancy.name.strip())]

    # Темы из формы не вычёркиваем: лишний раз сказать о сильной стороне
    # полезнее, чем сэкономить абзац. Решение Ивана 05.09.
    parts.extend(_themes_for(verdict.matched, vacancy.haystack, themes))

    if verdict.gaps:
        # Одна строка без извинений: пробел называется и сразу закрывается планом
        parts.append("Из требований вне опыта: " + "; ".join(verdict.gaps[:2])
                     + ". Закрываю это на собственном стенде.")

    parts.append(CLOSING)
    return "\n\n".join(parts)
