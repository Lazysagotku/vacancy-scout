"""Черновик сопроводительного письма.

Черновик, а не готовое письмо: собирается из подтверждённых фактов профиля
под то, что реально требует вакансия. Человек дочитывает, правит под компанию
и только тогда отправляет. Без markdown - hh форматирование не передаёт.
"""

from scout.hh import Vacancy
from scout.scoring import Verdict

OPENING = {
    "dev": "Откликаюсь на позицию {name}.\n\nСемь лет работаю в корпоративных системах "
           "финансового и государственного сектора, последние полтора года - разработчиком "
           "и специалистом третьей линии: бэкенд внутреннего ПО на C#, учётные балансы, "
           "платежи, проводки.",
    "support": "Откликаюсь на позицию {name}.\n\nСемь лет работаю в корпоративных системах "
               "финансового и государственного сектора. Работал на всех линиях поддержки, "
               "последние годы - на третьей: разбираю проблему от обращения пользователя "
               "до причины в коде.",
    "ai": "Откликаюсь на позицию {name}.\n\nСемь лет в корпоративных системах, последние "
          "месяцы - ежедневная разработка в связке с ИИ-инструментами: собственные сервисы, "
          "MCP-серверы под конкретные задачи, автоматизация процессов.",
}

CLOSING = ("Мои проекты: https://lazysagotku.github.io\n\n"
           "Готов обсудить детали.\n\n"
           "С уважением,\nИван Архипов")


def draft(vacancy: Vacancy, verdict: Verdict) -> str:
    """Собирает черновик. Для отсеянных вакансий письма нет - незачем."""
    if verdict.blockers:
        return ""

    track = verdict.track or "support"
    parts = [OPENING.get(track, OPENING["support"]).format(name=vacancy.name.lower())]

    if verdict.matched:
        parts.append("По вашим требованиям:")
        for name, proof in verdict.matched[:6]:
            parts.append(f"{name} - {proof}.")

    if verdict.gaps:
        parts.append("Скажу честно о том, чего нет: " + "; ".join(verdict.gaps[:3]) + ".")

    parts.append(CLOSING)
    return "\n\n".join(parts)
