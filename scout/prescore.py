# Ключи короче четырёх букв нельзя искать подстрокой: «ии» сидит внутри
# половины русских слов на «-ии», а «ai» - внутри email. Такие проверяем
# по границам слова, иначе секретарь набирает баллы за окончание.
# Плюс слова, которые сидят внутри чужих: intern - в Internal, 1c - в номерах
SHORT_KEYS = {"ии", "ai", "sre", "soc", "k8s", "c#", "sql", "intern", "1c", "1с", "1l"}


def _has(word: str, name: str) -> bool:
    if len(word) > 3 and word not in SHORT_KEYS:
        return word in name
    return re.search(r"(?<![\w#.])" + re.escape(word) + r"(?![\w#])", name) is not None


def prescore(item: dict) -> dict:
    """Возвращает оценку, вердикт и заметки по одной находке."""
    name = (item.get("name") or "").lower()
    notes: list[str] = []

    for word, reason in STOP:
        if _has(word, name):
            return {"score": 0, "verdict": "пропустить", "notes": reason}

    value = sum(weight for word, weight in GOOD.items() if _has(word, name))
    value = min(value, 85)                       # потолок: без описания выше не судим

    top = item.get("salary_to") or item.get("salary_from")
    if top and top < profile.SALARY_FLOOR:
        value = max(0, value - 25)
        notes.append(f"вилка ниже планки: {top // 1000}к")
    elif not top:
        notes.append("вилка не указана")

    if item.get("remote"):
        value += 5
        notes.append("удалёнка")

    # Уровень позиции - это пометка, а не минус к релевантности. «Младший
    # DevOps» по содержанию работы ровно то, что нужно, и штраф за слово
    # «младший» топил его ниже порога разбора. Решение Ивана: раз ищут
    # интерна, о ступени выше можно договориться на собеседовании.
    if any(w in name for w in ("junior", "младший", "джуниор")):
        notes.append("junior - метить на ступень выше")
    if any(w in name for w in ("стажер", "стажёр", "стажировк")) or _has("intern", name):
        notes.append("интерн - метить на ступень выше")

    if "Без опыта" in (item.get("experience") or ""):
        value = max(0, value - 15)
        notes.append("роль рассчитана на новичка")

    value = max(0, min(100, value))
    verdict = ("сильный матч" if value >= 60 else
               "стоит посмотреть" if value >= 35 else "слабый матч")
    return {"score": value, "verdict": verdict, "notes": "; ".join(notes)}
