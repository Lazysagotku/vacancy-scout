"""Профиль кандидата: что умею, что нет, что считать блокером.

Вынесен в отдельный модуль намеренно - это единственное место, которое
нужно править при изменении опыта. Скоринг ничего о кандидате не знает.
"""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Skill:
    """Навык с весом и подтверждением.

    weight - насколько сильно совпадение по этому навыку двигает оценку.
    proof   - чем подтверждается, попадает в объяснение и в письмо.
    """

    name: str
    weight: int
    proof: str
    aliases: tuple[str, ...] = ()

    def mentioned_in(self, text: str) -> bool:
        low = text.lower()
        return any(word.lower() in low for word in (self.name, *self.aliases))


